#!/usr/bin/env python3
"""Generate `src/examples/t2s.rs` from the Traditional-Simplified table ADR-0031 d.5 names.

The source is `../dictionary-collection/site/t2s.json`, generated there from ICU's
Traditional-Simplified transform. It is not dictionary content: it is a script mapping, and it is
committed here so the core builds without that repository.

    python3 -I core/xdict-core/tools/gen-t2s.py ../dictionary-collection/site/t2s.json

The output is deterministic: sorted by code point, one `(traditional, simplified)` pair per line.
Every entry must map exactly one character to exactly one character; a multi-character entry is
an error, because the store's match offsets are character offsets and the highlight relies on
the mapping preserving them.

The source's sha256 is pinned. A different table is refused unless `--accept-source` is given, and
accepting one means bumping NORMALIZER in `src/examples/mod.rs` and rebuilding every store: the
mapping is part of what a store means (ADR-0031 d.5).
"""

import hashlib
import json
import sys
from pathlib import Path

EXPECTED = "src/examples/t2s.rs"
# The table this file was generated from: the source's sha256. A different table would change the mapping
# without changing NORMALIZER, so existing stores (built with the old mapping) and new queries (normalised with
# the new one) could disagree; a substitution is refused unless the caller accepts it in words (audit, 2026-10-24).
PINNED = "7bc24bb616509c3b45e264646ad8151c086ebf105b04b61a3fedd43b93d6f246"


def rust_char(c: str) -> str:
    if c == "'":
        return "'\\''"
    if c == "\\":
        return "'\\\\'"
    # A control or format character written literally does not compile; the escape is always a valid scalar.
    if not c.isprintable():
        return f"'\\u{{{ord(c):x}}}'"
    return f"'{c}'"


def main() -> int:
    args = [a for a in sys.argv[1:] if a != "--accept-source"]
    accept = len(args) != len(sys.argv) - 1
    if len(args) != 1:
        print(f"usage: {sys.argv[0]} <t2s.json> [--accept-source]", file=sys.stderr)
        return 2
    source = Path(args[0])
    raw = source.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != PINNED and not accept:
        print(
            f"refusing: {source} has sha256 {digest}, not the pinned {PINNED}.\n"
            "A new table changes what every store means; bump NORMALIZER in src/examples/mod.rs and rebuild\n"
            "every store, then run again with --accept-source to record the new digest.",
            file=sys.stderr,
        )
        return 1
    table = json.loads(raw.decode("utf-8"))
    if not isinstance(table, dict):
        print("the table is not a JSON object", file=sys.stderr)
        return 1
    for traditional, simplified in table.items():
        if len(traditional) != 1 or len(simplified) != 1:
            print(f"not a single-character mapping: {traditional!r} -> {simplified!r}", file=sys.stderr)
            return 1
        if traditional == simplified:
            print(f"an identity mapping: {traditional!r}", file=sys.stderr)
            return 1
        if any(0xD800 <= ord(c) <= 0xDFFF for c in (traditional, simplified)):
            print(f"a surrogate code point, not a Unicode scalar: {traditional!r} -> {simplified!r}", file=sys.stderr)
            return 1
    items = sorted(table.items(), key=lambda item: ord(item[0]))
    lines = [
        "//! Traditional to simplified, one character to one character (ADR-0031 d.5).",
        "//!",
        f"//! Generated by `core/xdict-core/tools/gen-t2s.py` from the table that repository generated from",
        f"//! ICU's Traditional-Simplified transform; source sha256 `{digest}`.",
        "//! Do not edit by hand. Sorted by the traditional character; `normalize` looks it up by",
        "//! binary search. Each entry maps exactly one character to one, so a character offset is the",
        "//! same in the printed and the normalised text.",
        "",
        "/// The mappings, sorted by the traditional character.",
        "pub(crate) const T2S: &[(char, char)] = &[",
    ]
    for traditional, simplified in items:
        lines.append(f"    ({rust_char(traditional)}, {rust_char(simplified)}),")
    lines.extend(["];", ""])
    out = Path(__file__).resolve().parent.parent / EXPECTED
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out} with {len(items)} mappings")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
