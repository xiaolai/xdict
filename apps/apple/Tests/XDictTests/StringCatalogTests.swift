import Foundation
import Testing
import XDictTestSupport

/// **The string catalog is what a translator is given, and the UI ships in English and Simplified Chinese**
/// (plan-macos-v1, the owner's decision of 2026-10-14). Adapted from XiaolaiDict's `StringCatalogTests`. Four things
/// have to hold: what the code says is in the catalog (`Tools/strings.sh` puts it there), every entry is complete in
/// both languages, nothing below the view layer holds display text it could show untranslated, and what the catalog
/// holds reaches the bundle.
struct StringCatalogTests {
    static let catalogPath = "Strings/Localizable.xcstrings"
    /// The languages every entry must carry, the source language first.
    static let languages = ["en", "zh-Hans"]

    /// The view layer: prose written here is the reader's, however it was written.
    static let viewLayer = ["Sources/XDictUI"]
    /// The app and the entry view: read for literals at a localizing call site only. The rest of what they hold is
    /// instrument output and log text, which is not translated and would swamp the prose rule; the entry view's
    /// sentences are all `LocalizedStringResource`s, in `EntrySentences`.
    static let app = ["Sources/XDict", "Sources/XDictEntryView"]
    /// Below the view layer: no display text at all. What the service says reaches the reader only as a typed outcome
    /// the view layer words (`LaunchStatus`); the contract carries kinds and payloads, never a sentence (ADR-0007
    /// decision 10: sentences are the shell's).
    static let belowTheViewLayer = ["Sources/XDictBase", "Sources/XDictContract", "Sources/XDictService"]
    /// Neither: generated by UniFFI (no reader text), and the tests' own support.
    static let notScanned = ["XDictCore": "the UniFFI binding, generated, holding no reader-facing text",
                             "XDictTestSupport": "test support, which ships nothing",
                             "XDictEntryLab": "the development lab, an E2E instrument never in XDict.app, telling no reader anything"]

    // MARK: - The checks

    /// **Every string the reader sees is in the catalog.** A string added without `make strings` is one no translator
    /// ever sees, and nothing else would say so.
    @Test func everyLiteralTheReaderSeesIsInTheCatalog() throws {
        let strings = try Self.strings(Self.catalog())
        var missing: [String] = []
        for directory in Self.viewLayer + Self.app {
            let files = try SourceScan.files(under: Manifest.package.appending(path: directory))
            #expect(!files.isEmpty, "nothing scanned under \(directory)")
            for (file, text) in files {
                for literal in Self.literals(in: text) {
                    guard let rule = Self.rule(for: literal, inTheViewLayer: Self.viewLayer.contains(directory)),
                          strings[literal.text] == nil else { continue }
                    missing.append("\(file.lastPathComponent):\(literal.line) (\(rule)): \(literal.text)")
                }
            }
        }
        #expect(missing.isEmpty, "run `make strings`, then translate; the catalog does not have: \(missing)")
    }

    /// **Every entry is complete in English and in Simplified Chinese**: a translated unit with a value, in each, and
    /// no entry the source no longer says (`stale`, which `xcstringstool sync` marks and nothing would remove).
    @Test func everyEntryIsCompleteInBothLanguages() throws {
        let catalog = try Self.catalog()
        #expect(catalog["sourceLanguage"] as? String == "en")
        let strings = try Self.strings(catalog)
        #expect(!strings.isEmpty, "the catalog holds no strings, so completeness says nothing")
        #expect(Self.incomplete(strings) == [])
    }

    /// The control: an entry missing its Chinese, one whose Chinese is not yet translated, one with an empty English,
    /// and a stale one are each named; a complete one is not.
    @Test func anIncompleteEntryIsNamed() {
        func unit(_ value: String, _ state: String = "translated") -> [String: Any] {
            ["stringUnit": ["state": state, "value": value]]
        }
        let strings: [String: Any] = [
            "Complete": ["localizations": ["en": unit("Complete"), "zh-Hans": unit("完整")]],
            "No Chinese": ["localizations": ["en": unit("No Chinese")]],
            "Untranslated": ["localizations": ["en": unit("Untranslated"), "zh-Hans": unit("未", "needs_review")]],
            "Empty English": ["localizations": ["en": unit(""), "zh-Hans": unit("空")]],
            "Stale": ["extractionState": "stale", "localizations": ["en": unit("Stale"), "zh-Hans": unit("旧")]],
        ]
        #expect(Self.incomplete(strings) == [
            "Empty English: no translated en",
            "No Chinese: no translated zh-Hans",
            "Stale: stale — the source no longer says it; run make strings and remove it",
            "Untranslated: no translated zh-Hans",
        ])
    }

    /// **No display text below the view layer**: a sentence there could be shown and never extracted.
    @Test func noTargetBelowTheViewLayerHoldsDisplayText() throws {
        var offenders: [String] = []
        for directory in Self.belowTheViewLayer {
            let files = try SourceScan.files(under: Manifest.package.appending(path: directory))
            #expect(!files.isEmpty, "nothing scanned under \(directory)")
            offenders += try Self.filesHoldingDisplayText(files).map { "\(directory)/\($0)" }
        }
        #expect(offenders.isEmpty, "these belong in the view layer: \(offenders)")
    }

    /// **The lists name every target SwiftPM compiles, each once**, read off the manifest: a target added later and on
    /// no list is one no scan covers.
    @Test func everyTargetIsScannedOrNamedAsNot() throws {
        let compiled = try Manifest.dump().targets.values.filter { $0.type != "binary" && $0.type != "test" }.map(\.name)
        let listed = (Self.viewLayer + Self.app + Self.belowTheViewLayer).map { $0.replacingOccurrences(of: "Sources/", with: "") }
        #expect(Set(listed).count == listed.count, "a target on two lists: \(listed)")
        #expect(Set(compiled) == Set(listed).union(Self.notScanned.keys), """
            compiled: \(compiled.sorted()); scanned or named: \((listed + Self.notScanned.keys).sorted())
            """)
    }

    /// **And what the catalog holds reaches the reader**: the real catalog, compiled as the bundle compiles it, answers
    /// every key with its Chinese.
    @Test func theCatalogCompilesIntoTablesTheBundleReads() throws {
        let strings = try Self.strings(Self.catalog())
        let scratch = try TemporaryDirectory(named: "xdict-catalog")
        let (status, _, said) = try Manifest.run("/usr/bin/xcrun", [
            "xcstringstool", "compile", Manifest.package.appending(path: Self.catalogPath).path,
            "--output-directory", scratch.url.path,
        ])
        try #require(status == 0, "xcstringstool could not compile the catalog: \(said)")
        for language in Self.languages {
            let table = try #require(
                NSDictionary(contentsOf: scratch.appending("\(language).lproj/Localizable.strings")) as? [String: String],
                "no \(language).lproj/Localizable.strings was produced")
            for (key, entry) in strings {
                let wanted = Self.value(of: entry, in: language)
                #expect(table[key] == wanted, "\(language): \(key) compiles to \(table[key] ?? "nothing"), not \(wanted ?? "nothing")")
            }
        }
    }

    // MARK: - The scan's own controls

    /// **The scan reaches what it claims to.** Every rule is a filter, and a filter that has quietly stopped matching
    /// reads exactly like a codebase with nothing wrong in it.
    @Test func theScanSeesBothWaysAStringGoesMissing() throws {
        #expect(Self.isProse("Show All"))
        #expect(Self.isProse("About"), "one capitalised word is prose")
        #expect(Self.isProse("the dictionary did not answer"), "a sentence is prose whatever case it starts in")
        #expect(!Self.isProse("clock.arrow.circlepath"), "an SF Symbol name is not prose")
        #expect(!Self.isProse("CFBundleVersion"), "an interior capital makes it a key")
        #expect(!Self.isProse("ai.xdict.app"), "a bundle identifier is not prose")
        #expect(!Self.isProse("--handshake-report"), "a flag is not prose")

        let bare = Literal(line: 1, prefix: "    title: \"", text: "Show All")
        #expect(Self.rule(for: bare, inTheViewLayer: true) == "prose in the view layer")
        #expect(Self.rule(for: bare, inTheViewLayer: false) == nil, "the prose rule is the view layer's")
        let called = Literal(line: 1, prefix: "    Text(\"", text: "Show All")
        #expect(Self.rule(for: called, inTheViewLayer: false) == "written at a localizing call site")
        let said = Literal(line: 1, prefix: "    Text(verbatim: \"", text: "Show All")
        #expect(Self.rule(for: said, inTheViewLayer: true) == nil, "`verbatim:` says this is not prose")
        let note = Literal(line: 1, prefix: "    comment: \"", text: "Show All")
        #expect(Self.rule(for: note, inTheViewLayer: true) == nil, "a translator's note is not a key")

        #expect(Self.literals(in: "Text(\"One\") + Text(\"Two\")").map(\.text) == ["One", "Two"])
        #expect(Self.literals(in: "let s = \"Joined \"\n    + \"across lines\"").map(\.text) == ["Joined across lines"])
        #expect(Self.literals(in: "Text(\"\"\"\n    A long \\\n    sentence\n    \"\"\")").map(\.text) == ["A long sentence"])
    }

    /// The display-text predicate, on files of the test's own: nothing in an innocent file, and each spelling of a
    /// localizing initialiser — split across a line too — caught.
    @Test func theDisplayTextScanCatchesAPlantedLiteral() throws {
        // Composed, so this file does not match the search it is testing.
        let call = "String" + "("
        #expect(try Self.filesHoldingDisplayText([(URL(fileURLWithPath: "/Innocent.swift"), "let x = 1\n")]) == [])
        for (index, planted) in ["\(call)localized: \"planted\")", "\(call)\n    localized: \"split\")",
                                 "LocalizedStringResource" + "(\n \"resource\")", "LocalizedStringKey" + "(\"key\")",
                                 "NSLocalizedString" + "(\"old\", comment: \"\")"].enumerated() {
            let file = URL(fileURLWithPath: "/Planted\(index).swift")
            #expect(try Self.filesHoldingDisplayText([(file, "let planted = \(planted)\n")]) == [file.lastPathComponent],
                    "the scan did not see \(planted.debugDescription)")
        }
    }

    // MARK: - Reading the catalog

    static func catalog() throws -> [String: Any] {
        let data = try Data(contentsOf: Manifest.package.appending(path: catalogPath))
        return try #require(try JSONSerialization.jsonObject(with: data) as? [String: Any])
    }

    static func strings(_ catalog: [String: Any]) throws -> [String: Any] {
        try #require(catalog["strings"] as? [String: Any])
    }

    static func value(of entry: Any, in language: String) -> String? {
        let localizations = (entry as? [String: Any])?["localizations"] as? [String: Any]
        let unit = (localizations?[language] as? [String: Any])?["stringUnit"] as? [String: Any]
        guard unit?["state"] as? String == "translated", let value = unit?["value"] as? String, !value.isEmpty else {
            return nil
        }
        return value
    }

    static func incomplete(_ strings: [String: Any]) -> [String] {
        strings.keys.sorted().flatMap { key -> [String] in
            let entry = strings[key]
            if (entry as? [String: Any])?["extractionState"] as? String == "stale" {
                return ["\(key): stale — the source no longer says it; run make strings and remove it"]
            }
            return languages.compactMap { value(of: entry as Any, in: $0) == nil ? "\(key): no translated \($0)" : nil }
        }
    }

    // MARK: - Reading the source

    /// One string literal, and the text that stood in front of its opening quote.
    struct Literal {
        let line: Int
        /// Up to and including the opening quote, so a call site is recognised by what it ends with.
        let prefix: String
        let text: String
    }

    /// Every spelling that hands the compiler a key. A literal at one of these and not in the catalog is one no
    /// translator ever sees. `Text(verbatim:` deliberately matches none of them.
    static let localizingCallSites = [
        "String(localized: \"", "LocalizedStringResource(\"", "LocalizedStringKey(\"", "AttributedString(localized: \"",
        "Text(\"", "Label(\"", "Button(\"", "Toggle(\"", "Picker(\"", "TextField(\"", "Section(\"", "Link(\"",
        "Stepper(\"", "Menu(\"", "Tab(\"", "Window(\"", "WindowGroup(\"", "Settings(\"",
        "navigationTitle(\"", "accessibilityLabel(\"", "help(\"", "confirmationDialog(\"", "alert(\"",
    ]

    /// **Prose the reader is given no key for**: a sentence written as a plain `String` reaches the screen through
    /// `Text(_:)`'s `StringProtocol` overload, verbatim, and is never extracted. So every prose literal in the view
    /// layer must be a key however it was written. A digit, a path or markup character, or a dot between two letters
    /// makes it not prose; a space makes it prose; otherwise one capitalised word with no interior capital is prose.
    static func isProse(_ literal: String) -> Bool {
        guard let first = literal.first else { return false }
        if literal.contains(where: \.isNumber) { return false }
        if literal.contains(where: { "_/:@#\\%{}<>[]|=+*~$".contains($0) }) { return false }
        if literal.hasPrefix("-") { return false }
        var previous: Character?, beforePrevious: Character?
        for character in literal {
            if previous == ".", let beforePrevious, beforePrevious.isLetter, character.isLetter { return false }
            beforePrevious = previous
            previous = character
        }
        if literal.contains(" ") { return true }
        return first.isUppercase && !literal.dropFirst().contains(where: \.isUppercase)
    }

    /// Whether a literal is one the catalog has to answer for, and under which rule. Interpolated ones are skipped
    /// (their key holds format specifiers, which `everyEntryIsCompleteInBothLanguages` covers once extracted); a
    /// `comment:` is the translator's note, and `verbatim:` is the author saying this is not prose.
    static func rule(for literal: Literal, inTheViewLayer: Bool) -> String? {
        guard !literal.text.isEmpty, !literal.text.contains("\\("), !literal.text.contains("\\\"") else { return nil }
        if literal.prefix.hasSuffix("comment: \"") || literal.prefix.hasSuffix("verbatim: \"") { return nil }
        if localizingCallSites.contains(where: { literal.prefix.hasSuffix($0) }) { return "written at a localizing call site" }
        guard inTheViewLayer, isProse(literal.text) else { return nil }
        return "prose in the view layer"
    }

    /// Every literal in a file, with what preceded it: `"""` literals read whole (a closing delimiter strips its own
    /// indentation and a trailing `\` joins lines, as the compiler reads them), `+` continuations rejoined, comments
    /// skipped, and the rest of a line after an interpolated literal left alone (an interpolation can hold a literal of
    /// its own, and a walk over quotes cannot tell which quote closes which).
    static func literals(in text: String) -> [Literal] {
        let lines = text.components(separatedBy: .newlines)
        var found: [Literal] = []
        var index = 0
        while index < lines.count {
            let line = lines[index]
            if line.trimmingCharacters(in: .whitespaces).hasPrefix("//") { index += 1; continue }
            if let open = line.range(of: "\"\"\"") {
                var at = index + 1
                var body: [String] = []
                while at < lines.count, !lines[at].trimmingCharacters(in: .whitespaces).hasPrefix("\"\"\"") {
                    body.append(lines[at])
                    at += 1
                }
                guard at < lines.count else { index += 1; continue }
                let margin = lines[at].prefix { $0 == " " }.count
                var joined = ""
                for raw in body {
                    let stripped = String(raw.dropFirst(min(margin, raw.prefix { $0 == " " }.count)))
                    joined += stripped.hasSuffix("\\") ? String(stripped.dropLast()) : stripped + "\n"
                }
                if joined.hasSuffix("\n") { joined.removeLast() }
                found.append(Literal(line: index + 1, prefix: String(line[...open.lowerBound]), text: joined))
                index = at + 1
                continue
            }
            var cursor = line.startIndex
            var consumed = 0
            while let quote = line[cursor...].firstIndex(of: "\"") {
                let prefix = String(line[...quote])
                let rest = String(line[line.index(after: quote)...])
                guard var piece = literal(from: rest) else { break }
                var at = index
                var tail = String(rest.dropFirst(piece.count + 1))
                while at + 1 < lines.count {
                    let next = lines[at + 1].trimmingCharacters(in: .whitespaces)
                    let continues = tail.trimmingCharacters(in: .whitespaces).hasSuffix("+") || next.hasPrefix("+")
                    guard continues, let nextQuote = next.firstIndex(of: "\""),
                          let more = literal(from: String(next[next.index(after: nextQuote)...])) else { break }
                    piece += more
                    at += 1
                    tail = String(next[next.index(after: nextQuote)...].dropFirst(more.count + 1))
                }
                found.append(Literal(line: index + 1, prefix: prefix, text: piece))
                if piece.contains("\\(") { break }
                if at != index { consumed = at - index; break }
                let closing = line.index(line.index(after: quote), offsetBy: piece.count)
                cursor = line.index(after: closing)
            }
            index += consumed + 1
        }
        return found
    }

    /// The text up to the next quote.
    static func literal(from rest: String) -> String? {
        guard let end = rest.firstIndex(of: "\"") else { return nil }
        return String(rest[..<end])
    }

    /// The files whose code calls a localizing initialiser, comments and strings aside. **A pattern, not a spelling**:
    /// whitespace, a line break included, may stand anywhere Swift allows it inside the call.
    static func filesHoldingDisplayText(_ files: [(file: URL, text: String)]) throws -> [String] {
        let call = try Regex(#"\b(?:Attributed)?String\s*\(\s*localized\s*:|\bLocalizedString(?:Resource|Key)\s*\(|\bNSLocalizedString\s*\("#)
        return files.filter { SourceScan.codeOnly($0.text).contains(call) }.map(\.file.lastPathComponent).sorted()
    }
}
