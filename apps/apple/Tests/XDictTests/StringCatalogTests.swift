    // MARK: - Reading the catalog

    static func catalog() throws -> [String: Any] {
        let data = try Data(contentsOf: Manifest.package.appending(path: catalogPath))
        return try #require(try JSONSerialization.jsonObject(with: data) as? [String: Any])
    }

    static func strings(_ catalog: [String: Any]) throws -> [String: Any] {
        try #require(catalog["strings"] as? [String: Any])
    }

    static func unit(_ value: String, _ state: String = "translated") -> [String: Any] {
        ["stringUnit": ["state": state, "value": value]]
    }

    static func plural(_ forms: [String: String]) -> [String: Any] {
        ["variations": ["plural": forms.mapValues { unit($0) }]]
    }

    static func localization(_ entry: Any, _ language: String) -> [String: Any]? {
        ((entry as? [String: Any])?["localizations"] as? [String: Any])?[language] as? [String: Any]
    }

    /// A string unit's value, when it is translated and not empty.
    static func translated(_ unit: Any?) -> String? {
        let unit = (unit as? [String: Any])?["stringUnit"] as? [String: Any]
        guard unit?["state"] as? String == "translated", let value = unit?["value"] as? String, !value.isEmpty else {
            return nil
        }
        return value
    }

    /// The plural forms a localization holds: its own variation, and each substitution's.
    static func pluralForms(_ localization: [String: Any]) -> [[String: Any]] {
        var forms: [[String: Any]] = []
        if let own = (localization["variations"] as? [String: Any])?["plural"] as? [String: Any] { forms.append(own) }
        for case let substitution as [String: Any] in (localization["substitutions"] as? [String: Any])?.values.map({ $0 }) ?? [] {
            forms.append(((substitution["variations"] as? [String: Any])?["plural"] as? [String: Any]) ?? [:])
        }
        return forms
    }

    static func hasPlurals(_ entry: Any, in language: String) -> Bool {
        localization(entry, language).map { !pluralForms($0).isEmpty } ?? false
    }

    /// Whether some plural of the English differs between its forms ("entry" and "entries"; not "Show 1 More").
    static func formsDiffer(_ entry: Any) -> Bool {
        guard let english = localization(entry, "en") else { return false }
        return pluralForms(english).contains { forms in
            Set(forms.values.compactMap { translated($0)?.replacingOccurrences(of: "%arg", with: "") }
                .map { $0.replacingOccurrences(of: "%lld", with: "").replacingOccurrences(of: "%llu", with: "") }).count > 1
        }
    }

    /// An entry's plain value in a language; nil when it is missing or untranslated, or held as plural forms.
    static func value(of entry: Any, in language: String) -> String? {
        localization(entry, language).flatMap { translated($0) }
    }

    /// Whether a language's localization is whole: a translated value, or plural forms each translated with `other`
    /// among them (and, beside substitutions, the sentence that holds them).
    static func isComplete(_ entry: Any, in language: String) -> Bool {
        guard let localization = localization(entry, language) else { return false }
        let forms = pluralForms(localization)
        let ownPlural = (localization["variations"] as? [String: Any])?["plural"] != nil
        if !ownPlural, translated(localization) == nil { return false }
        return forms.allSatisfy { forms in forms["other"] != nil && forms.values.allSatisfy { translated($0) != nil } }
    }

    static func incomplete(_ strings: [String: Any]) -> [String] {
        strings.keys.sorted().flatMap { key -> [String] in
            let entry = strings[key]
            if (entry as? [String: Any])?["extractionState"] as? String == "stale" {
                return ["\(key): stale — the source no longer says it; run make strings and remove it"]
            }
            return languages.compactMap { isComplete(entry as Any, in: $0) ? nil : "\(key): no translated \($0)" }
        }
    }

    // MARK: - Counts

    /// An integer argument in a key, as `swiftc` writes one for an interpolated `Int` or `UInt64`.
    static var countSpecifier: Regex<Substring> { #/%(?:\d+\$)?(?:ll|l)?[du]/# }

    /// The integers that are not a count of something, each with why it needs no plural forms.
    static let notCounts: [String: String] = [
        "%lld of %lld": "a position in find's matches, \"3 of 7\": no noun to agree",
        "%lld of %llu shown": "how many of the results show, \"20 of 120 shown\": no noun to agree",
        "Dictionaries answering lookups: %lld.": "a label and its number",
        "Fonts kept: %lld": "a label and its number",
        "Style sheets read: %lld, skipped: %lld": "a label and its numbers",
        "XDict reading style, rules version %u.": "a version, not a count",
        "record %lld": "which record under a key, an ordinal label",
        "The Keychain refused to save the key (status %d).": "a Keychain status code, not a count",
        "The Keychain refused to remove the key (status %d).": "a Keychain status code, not a count",
        "The entry was cut at %llu bytes, so only the part before that was sent.": "a byte offset, not a count of a noun",
    ]

    /// The English entries whose format takes a count and that have no plural forms.
    static func countsWithoutPlurals(_ strings: [String: Any]) -> [String] {
        strings.keys.filter { key in
            key.contains(countSpecifier) && notCounts[key] == nil && !hasPlurals(strings[key] as Any, in: "en")
        }.sorted()
    }

    /// A compiled format read with every count `count` and every string "X", in `language`'s number format.
    static func render(_ format: String, key: String, count: Int, language: String) -> String {
        let specifiers = key.matches(of: #/%(?:\d+\$)?(ll|l)?([duf@])/#)
        let arguments: [any CVarArg] = specifiers.map { match -> any CVarArg in
            switch match.output.2 {
            case "@": "X" as NSString
            case "u": UInt64(count)
            case "f": Double(count)
            default: Int64(count)
            }
        }
        return String(format: format, locale: Locale(identifier: language), arguments: arguments)
    }

    // MARK: - Reading the source

    /// One string literal, and the text that stood in front of its opening quote.
    struct Literal {
        let line: Int
        /// Up to and including the opening quote, so a call site is recognised by what it ends with.
        let prefix: String
        let text: String
    }

    /// Every spelling that hands the compiler a key. A literal at one of these and not in the catalog is one no
    /// translator ever sees. `Text(verbatim:` deliberately matches none of them.
    static let localizingCallSites = [
        "String(localized: \"", "LocalizedStringResource(\"", "LocalizedStringKey(\"", "AttributedString(localized: \"",
        "Text(\"", "Label(\"", "Button(\"", "Toggle(\"", "Picker(\"", "TextField(\"", "Section(\"", "Link(\"",
        "Stepper(\"", "Menu(\"", "Tab(\"", "Window(\"", "WindowGroup(\"", "Settings(\"",
        "navigationTitle(\"", "accessibilityLabel(\"", "help(\"", "confirmationDialog(\"", "alert(\"",
    ]

    /// **Prose the reader is given no key for**: a sentence written as a plain `String` reaches the screen through
    /// `Text(_:)`'s `StringProtocol` overload, verbatim, and is never extracted. So every prose literal in the view
    /// layer must be a key however it was written. A digit, a path or markup character, or a dot between two letters
    /// makes it not prose; a space makes it prose; otherwise one capitalised word with no interior capital is prose.
    static func isProse(_ literal: String) -> Bool {
        guard let first = literal.first else { return false }
        if literal.contains(where: \.isNumber) { return false }
        if literal.contains(where: { "_/:@#\\%{}<>[]|=+*~$".contains($0) }) { return false }
        if literal.hasPrefix("-") { return false }
        var previous: Character?, beforePrevious: Character?
        for character in literal {
            if previous == ".", let beforePrevious, beforePrevious.isLetter, character.isLetter { return false }
            beforePrevious = previous
            previous = character
        }
        if literal.contains(" ") { return true }
        return first.isUppercase && !literal.dropFirst().contains(where: \.isUppercase)
    }

    /// Whether a literal is one the catalog has to answer for, and under which rule. Interpolated ones are skipped
    /// (their key holds format specifiers, which `everyEntryIsCompleteInBothLanguages` covers once extracted); a
    /// `comment:` is the translator's note, and `verbatim:` is the author saying this is not prose.
    static func rule(for literal: Literal, inTheViewLayer: Bool) -> String? {
        guard !literal.text.isEmpty, !literal.text.contains("\\("), !literal.text.contains("\\\"") else { return nil }
        if literal.prefix.hasSuffix("comment: \"") || literal.prefix.hasSuffix("verbatim: \"") { return nil }
        if localizingCallSites.contains(where: { literal.prefix.hasSuffix($0) }) { return "written at a localizing call site" }
        guard inTheViewLayer, isProse(literal.text) else { return nil }
        return "prose in the view layer"
    }

    /// Every literal in a file, with what preceded it: `"""` literals read whole (a closing delimiter strips its own
    /// indentation and a trailing `\` joins lines, as the compiler reads them), `+` continuations rejoined, comments
    /// skipped, and the rest of a line after an interpolated literal left alone (an interpolation can hold a literal of
    /// its own, and a walk over quotes cannot tell which quote closes which).
    static func literals(in text: String) -> [Literal] {
        let lines = text.components(separatedBy: .newlines)
        var found: [Literal] = []
        var index = 0
        while index < lines.count {
            let line = lines[index]
            if line.trimmingCharacters(in: .whitespaces).hasPrefix("//") { index += 1; continue }
            if let open = line.range(of: "\"\"\"") {
                var at = index + 1
                var body: [String] = []
                while at < lines.count, !lines[at].trimmingCharacters(in: .whitespaces).hasPrefix("\"\"\"") {
                    body.append(lines[at])
                    at += 1
                }
                guard at < lines.count else { index += 1; continue }
                let margin = lines[at].prefix { $0 == " " }.count
                var joined = ""
                for raw in body {
                    let stripped = String(raw.dropFirst(min(margin, raw.prefix { $0 == " " }.count)))
                    joined += stripped.hasSuffix("\\") ? String(stripped.dropLast()) : stripped + "\n"
                }
                if joined.hasSuffix("\n") { joined.removeLast() }
                found.append(Literal(line: index + 1, prefix: String(line[...open.lowerBound]), text: joined))
                index = at + 1
                continue
            }
            var cursor = line.startIndex
            var consumed = 0
            while let quote = line[cursor...].firstIndex(of: "\"") {
                let prefix = String(line[...quote])
                let rest = String(line[line.index(after: quote)...])
                guard var piece = literal(from: rest) else { break }
                var at = index
                var tail = String(rest.dropFirst(piece.count + 1))
                while at + 1 < lines.count {
                    let next = lines[at + 1].trimmingCharacters(in: .whitespaces)
                    let continues = tail.trimmingCharacters(in: .whitespaces).hasSuffix("+") || next.hasPrefix("+")
                    guard continues, let nextQuote = next.firstIndex(of: "\""),
                          let more = literal(from: String(next[next.index(after: nextQuote)...])) else { break }
                    piece += more
                    at += 1
                    tail = String(next[next.index(after: nextQuote)...].dropFirst(more.count + 1))
                }
                found.append(Literal(line: index + 1, prefix: prefix, text: piece))
                if piece.contains("\\(") { break }
                if at != index { consumed = at - index; break }
                let closing = line.index(line.index(after: quote), offsetBy: piece.count)
                cursor = line.index(after: closing)
            }
            index += consumed + 1
        }
        return found
    }

    /// The text up to the next quote.
    static func literal(from rest: String) -> String? {
        guard let end = rest.firstIndex(of: "\"") else { return nil }
        return String(rest[..<end])
    }

    /// The files whose code calls a localizing initialiser, comments and strings aside. **A pattern, not a spelling**:
    /// whitespace, a line break included, may stand anywhere Swift allows it inside the call.
    static func filesHoldingDisplayText(_ files: [(file: URL, text: String)]) throws -> [String] {
        let call = try Regex(#"\b(?:Attributed)?String\s*\(\s*localized\s*:|\bLocalizedString(?:Resource|Key)\s*\(|\bNSLocalizedString\s*\("#)
        return files.filter { SourceScan.codeOnly($0.text).contains(call) }.map(\.file.lastPathComponent).sorted()
    }
