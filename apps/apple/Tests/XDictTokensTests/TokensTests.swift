    }

    @Test func theBannersSideInsetIsTheScalesL() throws {
        #expect(Tokens.Space.l == 16)
        #expect(try Self.source("PronunciationBanner.swift").contains(".padding(.horizontal, Tokens.Space.l)"))
    }
}

/// Both faces of a token: what SwiftUI and AppKit are handed is the same role.
struct TokenValuesTests {
    @Test func aMeasuredRoleIsItsSizeWeightAndDesign() {
        let row = Tokens.TextRole.sidebarRowSelected
        #expect(row.pointSize == 13)
        #expect(row.nsFont.pointSize == 13)
        let serif = Tokens.TextRole.startPrompt.nsFont
        #expect(serif.pointSize == 18)
        #expect(serif.familyName != NSFont.systemFont(ofSize: 18).familyName, "\(serif) is not the serif design")
        #expect(Tokens.TextRole.didYouMean.nsFont.fontDescriptor.symbolicTraits.contains(.italic))
    }

    @Test func aSystemRoleIsTheReadersSize() {
        #expect(Tokens.TextRole.body.pointSize == nil)
        #expect(Tokens.TextRole.body.nsFont.pointSize == NSFont.preferredFont(forTextStyle: .body).pointSize)
    }

    @Test func aMeasuredColourFollowsTheAppearance() throws {
        func components(_ name: NSAppearance.Name) throws -> [CGFloat] {
            var out: [CGFloat] = []
            try #require(NSAppearance(named: name)).performAsCurrentDrawingAppearance {
                let rgb = Tokens.Colour.entryRule.nsColor.usingColorSpace(.sRGB)
                out = [rgb?.redComponent, rgb?.greenComponent, rgb?.blueComponent].compactMap { $0 }
            }
            return out.map { ($0 * 255).rounded() }
        }
        #expect(try components(.aqua) == [0x92, 0x92, 0x92])
        #expect(try components(.darkAqua) == [0x5C, 0x5C, 0x5C])
        #expect(Tokens.Colour.label.nsColor == NSColor.labelColor)
    }
}

/// **A Control-clicked word with no box is anchored on its line** (owner, 2026-10-18: the popover's arrow covered a
/// quarter of the word). The anchor is one reading line tall, centred on the click, so the arrow's tip lands on the
/// line's edge: the middle of the white space between two lines. The line is the reading style's own: `--xdict-base`
/// times `--xdict-leading`.
struct ClickedWordAnchorTests {
    static func cssNumber(_ name: String, in css: String) throws -> Double {
        let pattern = try Regex("--xdict-\(name):([0-9.]+)")
        let match = try #require(css.firstMatch(of: pattern), "\(name) is not in tokens.css")
        return try #require(Double(match.output[1].substring ?? ""))
    }

    @Test func theAnchorIsOneReadingLineCentredOnTheClick() throws {
        let css = try String(contentsOf: TokensFreshnessTests.apple.appending(path: "Sources/XDictEntryView/Style/tokens.css"),
                             encoding: .utf8)
        let line = try Self.cssNumber("base", in: css) * (try Self.cssNumber("leading", in: css))
        #expect(abs(Double(Tokens.Row.clickedWord) - line) < 0.001)
        #expect(abs(Double(Tokens.Inset.clickedWordRise) - line / 2) < 0.001)
    }
}
