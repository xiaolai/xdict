/// **The tokens are today's `Tokens/tokens.toml`** (`Tools/tokens.py`): the generated Swift and CSS each carry the
/// SHA-256 of the source they were made of, and a source edited without `Tools/tokens.py gen` fails here, as a style
/// file edited without its generator fails `EntryStyleFilesTests`. `gen --check` (`make test-tools`) compares the bytes.
struct TokensFreshnessTests {
    static let apple = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
        .deletingLastPathComponent()

    static func digest(_ data: Data) -> String { SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined() }

    static func source() throws -> Data { try Data(contentsOf: apple.appending(path: "Tokens/tokens.toml")) }

    @Test func theSwiftIsMadeOfTodaysSource() throws {
        #expect(Self.digest(try Self.source()) == Tokens.sourceDigest,
                "Tokens.swift is stale versus Tokens/tokens.toml: run Tools/tokens.py gen")
    }

    @Test func theCSSIsMadeOfTodaysSource() throws {
        let css = try String(contentsOf: Self.apple.appending(path: "Sources/XDictEntryView/Style/tokens.css"),
                             encoding: .utf8)
        #expect(css.hasPrefix("/* Generated by Tools/tokens.py from Tokens/tokens.toml (sha256 \(Self.digest(try Self.source())))"),
                "tokens.css is stale versus Tokens/tokens.toml: run Tools/tokens.py gen")
    }

    /// The positive control: one byte more in the source is a different digest, so the two checks above can fail.
    @Test func anEditedSourceIsSeenAsStale() throws {
        var edited = try Self.source()
        edited.append(contentsOf: Array("\n".utf8))
        #expect(Self.digest(edited) != Tokens.sourceDigest)
    }
}

/// **The two visible changes the owner approved (2026-10-18) are the scale's tokens**, read off the sources: the
/// Acknowledgments' notices 12 pt apart (were 10), the pronunciation banner 16 pt in on each side (was 14).
struct ApprovedChangesTests {
    static func source(_ file: String) throws -> String {
        try String(contentsOf: TokensFreshnessTests.apple.appending(path: "Sources/XDictUI/\(file)"), encoding: .utf8)
    }

    @Test func theAcknowledgmentsSpacingIsTheScalesM() throws {
        #expect(Tokens.Space.m == 12)
