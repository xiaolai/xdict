// swift-tools-version: 6.2
import PackageDescription

// XDict for macOS: the shell around the Rust core (ADR-0003), which runs in a sandboxed XPC service and never in the
// app (AGENTS.md; plan-macos-v1 WI-2). `make` builds the core first (`Tools/build-core.sh` writes `Generated/`, which
// two targets below are made of), then tests, then assembles, signs and verifies XDict.app (`Tools/build-bundle.sh`).
let package = Package(
    name: "XDict",
    // The floor, decided in AGENTS.md: macOS 27. `PlatformFloorTests` holds this, both Info.plists and every binary the
    // bundle carries to the same number, so raising any one of them alone fails.
    platforms: [.macOS("27.0")],
    targets: [
        // What the app and the service share, and no domain vocabulary beyond it: the bundle identities, and the values
        // the launch window shows (the core's versions, and how asking for them failed). No framework at all.
        .target(name: "XDictBase"),

        // **The design tokens** (`Tokens/tokens.toml`): every length, size, text role and colour the shell draws with,
        // each Apple-measured, the system's or reasoned. `Tokens.swift` is generated by `Tools/tokens.py gen`, never
        // edited; `TokenTypes.swift` is the two value types it uses. AppKit and SwiftUI, nothing of this package.
        .target(name: "XDictTokens"),

        // **The IPC contract between the app and the service, frozen at WI-1** (ADR-0009): the NSXPC protocols and
        // their interfaces, the versioned envelopes, the records both sides exchange, the error kinds, the limits and
        // the deadlines. Foundation only, and no other target of this package: the app compiles it without the core,
        // and the service converts the core's types into it (`ModuleBoundaryTests` holds both).
        .target(name: "XDictContract"),

        // The view layer, apart from the app so Xcode can preview it. Reader-facing text lives here and in the app,
        // and nowhere below (`StringCatalogTests`). The main window (plan-macos-v1 WI-6) hosts the entry view.
        .target(name: "XDictUI", dependencies: ["XDictAnywhere", "XDictCapture", "XDictCaptureMac", "XDictAppleSource", "XDictBase", "XDictContract", "XDictEntryView",
                                                "XDictLibrary", "XDictSearch", "XDictSpeech", "XDictTokens"]),

        // **The main window's model** (plan-macos-v1 WI-6): a search over every enabled dictionary or one, each
        // dictionary looked up on its own and its results painted as they arrive (Q12), paged to every record (Q10);
        // why a dictionary has nothing to show, as a kind with its next action (Q11); suggestions; the trail of entries
        // read, with Back, Forward and the original word (I7, I8); and the entry view fed from the service
        // (`ServiceEntryContent`, behind the entry view's own seam). Kinds, never sentences: the view layer words them.
        .target(name: "XDictSearch", dependencies: ["XDictClient", "XDictContract", "XDictEntryView", "XDictLibrary",
                                                    "XDictSpeech"]),

        // **The entry view and its confinement** (plan-macos-v1 WI-4; ADR-0009 decision 7; ADR-0007 decision 14): a
        // `WKWebView` per open dictionary, its `xdict:` scheme handler, the core's policy as a header on every response,
        // the rule list, the navigation and UI delegates, the two WebKit switches read back before anything renders, the
        // reader's consent before a remote link leaves, find, zoom and appearance. Its own target because it binds
        // WebKit and AppKit, which nothing else in the view layer does. It gets bytes through `EntryContent`, never the
        // contract's types, so the service's client plugs in without the view knowing the wire (WI-3, WI-6).
        // `Style/` is compiled in as text by Tools/reading-style-gen.py (`EntryStyleFiles.swift`), never read at run time.
        .target(name: "XDictEntryView", dependencies: ["XDictBase", "XDictTokens"], exclude: ["Style"]),

        // **Sound and speech** (plan-macos-v1 WI-7; `platform-architecture.md` §4a): the system's voices and which one
        // speaks a dictionary's declared language in the reader's accent, the reader's accent kept, and the output where
        // sound leaves the app (`AVAudioFile` and `AVAudioEngine` for a dictionary's recordings, `AVSpeechSynthesizer`
        // for the voice), behind a seam the window's pronunciation is tested through without a sound. Knows no
        // dictionary and no wire.
        .target(name: "XDictSpeech", dependencies: ["XDictBase"]),

        // **Lookup from anywhere** (plan-macos-v1 WI-8), moved from XiaolaiDict and re-checked against the MDX-first
        // model (ADR-0001): the lookup shortcut — the combination, the reader's choice kept, Carbon's exclusive hot key
        // behind a seam, the one Escape claim, and what registering it answered — the selection read through the
        // Accessibility API (both dialects, the term less its punctuation, and where it is on screen), the text the
        // Service is handed, and where the panel goes beside the word. Kinds, never sentences: the view layer words them.
        // Since plan-capture WI-3 also the composition layer for capture (ADR-0014 decision 5): hover's control, its
        // stored policy and scripts, the tokens' tolerances, and the popover's acknowledgements.
        .target(name: "XDictAnywhere", dependencies: ["XDictBase", "XDictCapture", "XDictCaptureMac", "XDictTokens"]),

        // **Capture, as values and arithmetic** (ADR-0014 decision 5; plan-capture WI-1), ported from XiaolaiDict's
        // `CaptureModel` and `Capture`: the captured term and its validating constructor, the sink's request numbers and
        // one terminal acknowledgement, hover's policy and session, geometry, line joining, tiling and the sentence around
        // a word. Foundation, CoreGraphics, NaturalLanguage, os and Synchronization only: no AppKit, no `XDictTokens`
        // (tolerances are handed in, `CaptureMetrics`), and no lookup, search, client, contract or UI target, held
        // transitively by `ModuleBoundaryTests`. Provenance per file: `Sources/XDictCapture/PROVENANCE.md`.
        .target(name: "XDictCapture", exclude: ["PROVENANCE.md"]),

        // **Capture on macOS** (ADR-0014 decisions 5 to 7; plan-capture WI-2), ported from XiaolaiDict's `MacCapture`
        // and moved down from `XDictAnywhere`: the Accessibility session and the one lane every out-of-process read takes,
        // the selection reader, the word reader's three dialects, and the never-prompting permission probe. AppKit and
        // Accessibility, the pure target and the identities; never ScreenCaptureKit or Vision (WI-4), the tokens, search,
        // the client, the contract or a view, held transitively by `ModuleBoundaryTests`. Provenance per file:
        // `Sources/XDictCaptureMac/PROVENANCE.md`.
        .target(name: "XDictCaptureMac", dependencies: ["XDictBase", "XDictCapture"], exclude: ["PROVENANCE.md"]),

        // **The app's side of the contract** (plan-macos-v1 WI-3): `ServiceClient` — request ids, deadlines, credits,
        // generations per caller, reconnection, handles reopened after a restart, payload ceilings — over a transport
        // seam (NSXPC, or a test's fake), and the tokens it sends. No core: it asks the service.
        .target(name: "XDictClient", dependencies: ["XDictBase", "XDictContract"]),

        // The development instruments' scenarios (the E2E `service` stage): the conformance fixtures answered through the
        // contract, and the service's checks that need a real service — a kill, a stall, a racing idle timer. They ship
        // in the app, as the handshake report does: they read only the fixtures they are pointed at.
        .target(name: "XDictInstruments", dependencies: ["XDictClient", "XDictContract", "XDictLibrary",
                                                        "XDictSearch"]),

        // **The reader's library** (plan-macos-v1 WI-5; ADR-0009 decision 2: the app's own, in its Application Support):
        // which files make each dictionary and where they are now (a security-scoped bookmark and a file id per file),
        // packages found in what the reader chose and kept inside it, imports with progress, cancel and retry, the
        // order, names, languages and enablement, a changed edition recognised, and lineage joins made only by the
        // reader and undone exactly. Kinds, never sentences: the view layer words them. No core: it asks the service.
        .target(name: "XDictLibrary", dependencies: ["XDictAppleSource", "XDictClient", "XDictContract"]),

        // **What the app and the service both say about an Apple dictionary's files** (ADR-0011 decisions 4, 7, 9 and
        // 11): the bounded walk and the versioned manifest hash (the source revision), written once so the app compares
        // an installed bundle with what the service stamped by the same code; the installed bundles found under the
        // AssetsV2 path; the app's byte-for-byte copy into the shared container, and the launch sweep of it. It reads
        // names, sizes, bytes and `Info.plist`, never a bundle's data, which only the converter parses.
        .target(name: "XDictAppleSource", dependencies: ["XDictContract"]),

        // The app: not sandboxed, Developer ID, hardened runtime. **It never links the core** — it asks the service.
        .executableTarget(name: "XDict", dependencies: ["XDictAnywhere", "XDictCapture", "XDictCaptureMac", "XDictAppleSource", "XDictBase", "XDictClient", "XDictContract", "XDictEntryView",
                                                        "XDictInstruments", "XDictLibrary", "XDictSearch", "XDictSpeech",
                                                        "XDictTokens", "XDictUI"]),

        // **A development instrument, never in XDict.app** (`Tools/build-lab.sh`, `Tools/build-bundle.sh` holds the app
        // to its two executables): the production entry view, fed by the core linked in directly, so the E2E stages can
        // render the hostile battery and real dictionaries before the service answers entries (WI-3). It is the only
        // place a confinement layer can be switched off (`--disable-layer`), for the isolated per-layer controls.
        .executableTarget(name: "XDictEntryLab", dependencies: ["XDictCore", "XDictEntryView", "XDictTokens"]),

        // **The core, and who may reach it.** `xdictFFI` is libxdict_ffi.a and its C header as an XCFramework, and
        // `XDictCore` the UniFFI binding generated from that archive; both are written by `Tools/build-core.sh` into
        // `Generated/`, which is untracked. A binary target is how SwiftPM takes a prebuilt archive without
        // `unsafeFlags`, and it links the archive statically into what depends on it. Only `XDictService` does (and
        // its tests): `ModuleBoundaryTests` refuses any other target that reaches either module, by the graph and by
        // its imports, and `Tools/build-bundle.sh` refuses an app binary carrying a core symbol.
        .binaryTarget(name: "xdictFFI", path: "Generated/xdictFFI.xcframework"),
        .target(
            name: "XDictCore",
            dependencies: ["xdictFFI"],
            path: "Generated/XDictCore",
            // What the archive asks of the system besides libSystem (`--print native-static-libs`).
            linkerSettings: [.linkedLibrary("iconv")]),

        // The dictionary service: sandboxed, with no file and no network entitlement, and the only process that runs
        // the core (ADR-0001 decision 5), answering the frozen contract.
        .executableTarget(name: "XDictService", dependencies: ["XDictAppleImport", "XDictAppleSource", "XDictBase", "XDictContract", "XDictCore"]),

        // **Apple's dictionaries, converted to MDX once** (ADR-0011): a snapshot of an installed `*.dictionary` bundle in
        // the service's own container, written out as an `.mdx` + `.mdd` pair the core then reads like any other. Swift,
        // not the core, because only macOS has these bundles (ADR-0011 decision 3); linked by the dictionary service
        // alone, since a bundle is untrusted binary input (ADR-0001), and `ModuleBoundaryTests` holds that. Foundation
        // and the system's libz, nothing else.
        .target(name: "XDictAppleImport"),

        // What the test targets share, and nothing ships: a source walk that cannot skip silently, a directory that
        // removes itself, and the manifest as SwiftPM reads it.
        .target(name: "XDictTestSupport", path: "Tests/Support"),
        .testTarget(name: "XDictBaseTests", dependencies: ["XDictBase"]),
        // The tokens against their source: the generated file made of today's tokens.toml, and both faces of a role.
        .testTarget(name: "XDictTokensTests", dependencies: ["XDictTokens"]),
        // The client against services of the tests' own: fakes of the transport, and NSXPC listeners in this process.
        .testTarget(name: "XDictClientTests", dependencies: ["XDictBase", "XDictClient", "XDictContract"]),
        // The contract as the app sees it, with no core: envelopes, files, identity, admission, the NSXPC interfaces.
        .testTarget(name: "XDictContractTests", dependencies: ["XDictContract"]),
        .testTarget(name: "XDictUITests", dependencies: ["XDictAnywhere", "XDictCapture", "XDictCaptureMac", "XDictAppleSource", "XDictBase", "XDictContract", "XDictLibrary", "XDictSearch",
                                                        "XDictSpeech", "XDictTestSupport", "XDictUI"]),
        // The library without a service: packages found on disk, bookmarks across a move, languages, names, the
        // document, refusals and sounds; the model against a fake of the service.
        .testTarget(name: "XDictLibraryTests", dependencies: ["XDictAppleSource", "XDictClient", "XDictContract",
                                                             "XDictLibrary"]),
        // The installed bundles found, copied and swept over synthetic AssetsV2 trees the tests write (no Apple
        // content), and the manifest the app and the service share.
        .testTarget(name: "XDictAppleSourceTests", dependencies: ["XDictAppleSource", "XDictContract", "XDictTestSupport"]),
        // The main window's model against a fake of the service: scope, order, painting as each answers, paging,
        // unavailable dictionaries, suggestions, the trail, and the entry view's content over the contract.
        .testTarget(name: "XDictSearchTests", dependencies: ["XDictClient", "XDictContract", "XDictEntryView",
                                                             "XDictLibrary", "XDictSearch", "XDictSpeech"]),
        // The voices this Mac lists and the choice among them, the accent kept, and recordings opened as macOS opens them
        // — never played and never spoken: the build Mac makes no sound (the E2E `sound` stage plays and speaks).
        .testTarget(name: "XDictSpeechTests", dependencies: ["XDictSpeech"]),
        // Capture without a window server: the ported XiaolaiDict tests by name, and ADR-0014's objection checks.
        .testTarget(name: "XDictCaptureTests", dependencies: ["XDictCapture"]),
        // Capture on macOS against scripted Accessibility trees and a fake lane clock: never a window, never the real
        // Accessibility API, never this Mac's grant.
        .testTarget(name: "XDictCaptureMacTests", dependencies: ["XDictCapture", "XDictCaptureMac"]),
        // Lookup from anywhere without a keyboard, a window or another app: Carbon faked (a real global shortcut would
        // be taken from the reader while the suite ran), the Accessibility API faked, the panel's geometry as numbers.
        .testTarget(name: "XDictAnywhereTests", dependencies: ["XDictAnywhere", "XDictCapture", "XDictCaptureMac", "XDictTokens"]),
        // The entry view's decisions, without a window or a web view (the build Mac opens neither): routing and refusal,
        // the policy on every response, the rule list, the navigation table, the switches' read-back, link routing, the
        // consent gate, find's counting and the readability rule (their JavaScript in JavaScriptCore), preferences.
        .testTarget(name: "XDictEntryViewTests", dependencies: ["XDictEntryView", "XDictTokens"]),
        // The one test target besides the service that reaches the core: the service's own listener, over a real NSXPC
        // connection in this process, asked through the real client and the instruments' scenarios; and the core's
        // types mapped into the contract's.
        .testTarget(name: "XDictServiceTests", dependencies: ["XDictAppleImport", "XDictAppleSource", "XDictClient", "XDictContract", "XDictCore",
                                                              "XDictInstruments", "XDictService", "XDictTestSupport"]),
        // The converter over synthetic bundles the tests write themselves (no Apple content, ADR-0011): the bundle's
        // structure, the entry transform, the writer, its bounds, refusals and determinism, read back by a reader that
        // lives here and never ships (ADR-0011 decision 3).
        .testTarget(name: "XDictAppleImportTests", dependencies: ["XDictAppleImport", "XDictTestSupport"]),
        // The harness's own rules, read off the tree: module boundaries, test floors, the string catalog, the floor.
        .testTarget(name: "XDictTests", dependencies: ["XDictTestSupport"]),
    ],
    swiftLanguageModes: [.v6]
)

// **A warning is an error in every target this package compiles, and a file imports every module whose members it
// uses** (`MemberImportVisibility`). Set here, after the list, so a target added later is covered without anyone
// remembering to; `ModuleBoundaryTests` asks SwiftPM's own reading of the manifest that every target has both. A binary
// target compiles nothing and takes no settings. `Tools/compiler-warnings.py` catches what `treatAllWarnings` lets
// through (XiaolaiDict ADR-0052).
for target in package.targets where target.type != .binary {
    target.swiftSettings = (target.swiftSettings ?? []) + [
        .treatAllWarnings(as: .error), .enableUpcomingFeature("MemberImportVisibility"),
    ]
}
