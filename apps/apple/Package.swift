// swift-tools-version: 6.2
import PackageDescription

// XDict for macOS: the shell around the Rust core (ADR-0003), which runs in a sandboxed XPC service and never in the
// app (AGENTS.md; plan-macos-v1 WI-2). `make` builds the core first (`Tools/build-core.sh` writes `Generated/`, which
// two targets below are made of), then tests, then assembles, signs and verifies XDict.app (`Tools/build-bundle.sh`).
let package = Package(
    name: "XDict",
    // The floor, decided in AGENTS.md: macOS 27. `PlatformFloorTests` holds this, both Info.plists and every binary the
    // bundle carries to the same number, so raising any one of them alone fails.
    platforms: [.macOS("27.0")],
    // The Codex sign-in contract and the AI providers (sayso, ISC): the one OpenAI-compatible client with its provider
    // profiles and model catalogue, the reader's Claude and Codex CLIs, and Apple's on-device model. Pinned exactly;
    // sayso is early and its states are the contract. 0.5.1 fixes the Codex home's creation order: the probe read the
    // sign-in before the folder that holds it existed, and a fresh install showed the generic "codex" failure.
    dependencies: [
        .package(url: "https://github.com/xiaolai/sayso", exact: "0.5.1"),
    ],
    targets: [
        // What the app and the service share, and no domain vocabulary beyond it: the bundle identities, and the values
        // the launch window shows (the core's versions, and how asking for them failed). No framework at all.
        .target(name: "XDictBase"),

        // **The AI contract's values** (ADR-0021; `conformance/ai/`): the marking rule, the template composer with the
        // fixed response contract, the answer validator and schema, the shipped defaults, and the adapter that binds
        // sayso's Apple provider to `AppleAnswer`. The providers themselves are sayso's (SaySoAI, SaySoAICLI,
        // SaySoAIApple), re-exported; no UI text and no network policy beyond them.
        .target(name: "XDictAI", dependencies: [
            .product(name: "SaySoAI", package: "sayso"),
            .product(name: "SaySoAICLI", package: "sayso"),
            .product(name: "SaySoAIApple", package: "sayso"),
        ]),

        // **The design tokens** (`Tokens/tokens.toml`): every length, size, text role and colour the shell draws with,
        // each Apple-measured, the system's or reasoned. `Tokens.swift` is generated by `Tools/tokens.py gen`, never
        // edited; `TokenTypes.swift` is the two value types it uses. AppKit and SwiftUI, nothing of this package.
        .target(name: "XDictTokens"),

        // **The IPC contract between the app and the service, frozen at WI-1** (ADR-0009): the NSXPC protocols and
        // their interfaces, the versioned envelopes, the records both sides exchange, the error kinds, the limits and
        // the deadlines. Foundation only, and no other target of this package: the app compiles it without the core,
