        // the rule list, the navigation and UI delegates, the two WebKit switches read back before anything renders, the
        // reader's consent before a remote link leaves, find, zoom and appearance. Its own target because it binds
        // WebKit, which no other view-layer target does (the AppKit it also binds is that layer's ordinary currency). It
        // gets bytes through `EntryContent`, never the
        // contract's types, so the service's client plugs in without the view knowing the wire (WI-3, WI-6).
        // `Style/` is compiled in as text by Tools/reading-style-gen.py (`EntryStyleFiles.swift`), never read at run time.
        .target(name: "XDictEntryView", dependencies: ["XDictBase", "XDictTokens"], exclude: ["Style"]),

        // **Sound and speech** (plan-macos-v1 WI-7; `platform-architecture.md` §4a): the system's voices and which one
        // speaks a dictionary's declared language in the reader's accent, the reader's accent kept, and the output where
        // sound leaves the app (`AVAudioFile` and `AVAudioEngine` for a dictionary's recordings, `AVSpeechSynthesizer`
        // for the voice), behind a seam the window's pronunciation is tested through without a sound. Knows no
        // dictionary and no wire.
        .target(name: "XDictSpeech", dependencies: ["XDictBase"]),

        // **Core Spotlight's index** (plan-setup-v2 WI-6; ADR-0028, owner's decision of 2026-10-22: headwords only): the
        // words of the reader's dictionaries, opt-in and on this Mac, and nothing about their entries. Foundation and
        // CoreSpotlight, no AppKit: the builder, the index behind a seam, the batching, and the reader's switch.
        .target(name: "XDictSpotlight"),

        // **Lookup from anywhere** (plan-macos-v1 WI-8), moved from XiaolaiDict and re-checked against the MDX-first
        // model (ADR-0001): the lookup shortcut — the combination, the reader's choice kept, Carbon's exclusive hot key
        // behind a seam, the one Escape claim, and what registering it answered — the selection read through the
        // Accessibility API (both dialects, the term less its punctuation, and where it is on screen), the text the
        // Service is handed, and where the panel goes beside the word. Kinds, never sentences: the view layer words them.
        // Since plan-capture WI-3 also the composition layer for capture (ADR-0014 decision 5): hover's control, its
        // stored policy and scripts, the tokens' tolerances, and the popover's acknowledgements.
        .target(name: "XDictAnywhere", dependencies: ["XDictBase", "XDictCapture", "XDictCaptureMac", "XDictTokens"]),

        // **Capture, as values and arithmetic** (ADR-0014 decision 5; plan-capture WI-1), ported from XiaolaiDict's
        // `CaptureModel` and `Capture`: the captured term and its validating constructor, the sink's request numbers and
        // one terminal acknowledgement, hover's policy and session, geometry, line joining, tiling and the sentence around
        // a word. Foundation, CoreGraphics, NaturalLanguage, os and Synchronization only: no AppKit, no `XDictTokens`
        // (tolerances are handed in, `CaptureMetrics`), and no lookup, search, client, contract or UI target, held
