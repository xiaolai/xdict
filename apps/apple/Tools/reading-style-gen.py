#!/usr/bin/env python3
"""Compile the reading style's files into the entry view (plan-verification §4.6).

    python3 -I Tools/reading-style-gen.py            write Sources/XDictEntryView/EntryStyleFiles.swift
    python3 -I Tools/reading-style-gen.py --check    exit 1 if that file is not what the files make

`Sources/XDictEntryView/Style/` holds the frame's CSS and the shell's scripts as text a person edits. The app never
reads them at run time: their text is compiled into the binary as string literals here, so production has no style
file on disk to replace, and no `Bundle.module` lookup. Only the development lab reads a directory of them instead
(`--style-dir`), and `EntryStyleFilesTests` holds the compiled text to the files byte for byte.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
STYLE = os.path.join(HERE, "..", "Sources", "XDictEntryView", "Style")
OUT = os.path.join(HERE, "..", "Sources", "XDictEntryView", "EntryStyleFiles.swift")


def literal(text):
    """A Swift raw multi-line literal for `text`, exactly: enough `#`s that no `"#…` inside closes it and no `\\#…`
    inside escapes."""
    hashes = 1
    while '"' + "#" * hashes in text or "\\" + "#" * hashes in text:
        hashes += 1
    fence = "#" * hashes
    return fence + '"""\n' + text + '\n"""' + fence


def render():
    names = sorted(n for n in os.listdir(STYLE) if n.endswith((".css", ".js")))
    if not names:
        sys.exit("reading-style-gen: no .css or .js files in " + STYLE)
    lines = [
        "// Generated by Tools/reading-style-gen.py from Style/. Do not edit: edit the file, then run the script.",
        "// swiftlint:disable all",
        "",
        "/// The reading style's files, as compiled into the binary (`EntryStyle.bundled`).",
        "enum EntryStyleFiles {",
        "    static let text: [String: String] = [",
    ]
    for name in names:
        with open(os.path.join(STYLE, name), encoding="utf-8", newline="") as f:
            text = f.read()
        if "\r" in text:
            sys.exit("reading-style-gen: " + name + " has a carriage return")
        lines.append('        "' + name + '": ' + literal(text) + ",")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main():
    text = render()
    if sys.argv[1:] == ["--check"]:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                sys.exit("reading-style-gen: EntryStyleFiles.swift is stale; run Tools/reading-style-gen.py")
        return
    if sys.argv[1:]:
        sys.exit(__doc__)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)


main()
